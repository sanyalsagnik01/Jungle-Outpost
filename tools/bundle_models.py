#!/usr/bin/env python3
"""Pack every models/*.glb into models/models.bundle.js (base64).

Browsers refuse to fetch files when index.html is opened straight from disk, so the game reads
models from this bundle first. Re-run after changing any .glb:   python tools/bundle_models.py
(The Blender build scripts call the same function automatically.)"""
import base64, glob, os, sys


def bundle(models_dir):
    out = ['/* generated by tools/bundle_models.py - do not edit */', 'window.JO_MODEL_DATA = {']
    names = sorted(glob.glob(os.path.join(models_dir, '*.glb')))
    for p in names:
        with open(p, 'rb') as f: data = base64.b64encode(f.read()).decode('ascii')
        out.append('  "%s": "%s",' % (os.path.splitext(os.path.basename(p))[0], data))
    out.append('};')
    dst = os.path.join(models_dir, 'models.bundle.js')
    with open(dst, 'w', newline='\n') as f: f.write('\n'.join(out) + '\n')
    return dst, len(names), os.path.getsize(dst)


if __name__ == '__main__':
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'models')
    print('wrote %s (%d models, %d bytes)' % bundle(os.path.normpath(root if len(sys.argv) < 2 else sys.argv[1])))
